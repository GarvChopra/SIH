"""Evidence file storage.

Files are written OUTSIDE `static/` and served only through the authorised
`/files/<id>` route, so a guessed URL never exposes a complaint document.
"""
from __future__ import annotations

import os
import secrets

from services.errors import ValidationError

UPLOAD_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "uploads")
ALLOWED = {".pdf", ".png", ".jpg", ".jpeg", ".txt", ".doc", ".docx"}
MAX_BYTES = 5 * 1024 * 1024
MAX_FILES = 5


def save(file_storage) -> tuple[str, str]:
    """Validate and store one uploaded file. Returns (display_name, stored_name)."""
    name = os.path.basename((file_storage.filename or "").strip())
    ext = os.path.splitext(name)[1].lower()
    if not name or ext not in ALLOWED:
        raise ValidationError(f"{name or 'file'}: allowed types are PDF, images, TXT, DOC(X)")
    data = file_storage.read(MAX_BYTES + 1)
    if len(data) > MAX_BYTES:
        raise ValidationError(f"{name}: file is larger than 5 MB")
    if not data:
        raise ValidationError(f"{name}: file is empty")
    os.makedirs(UPLOAD_DIR, exist_ok=True)
    stored = f"{secrets.token_hex(12)}{ext}"
    with open(os.path.join(UPLOAD_DIR, stored), "wb") as fh:
        fh.write(data)
    return name[:120], stored


def path_for(stored_name: str) -> str:
    # stored names are generated by save(); reject anything else outright
    if os.path.basename(stored_name) != stored_name:
        raise ValidationError("bad file reference")
    return os.path.join(UPLOAD_DIR, stored_name)
